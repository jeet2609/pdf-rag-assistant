"""
RAG Evaluation Module

Responsibilities:
- Load semantic similarity model
- Calculate answer similarity
- Evaluate RAG responses
"""

from config.settings import settings
from sentence_transformers import SentenceTransformer
from sentence_transformers.util import cos_sim
from src.embeddings import get_device


def load_similarity_model() -> SentenceTransformer:
	"""
	Load the sentence embedding model used for evaluation.

	Returns:
		Loaded SentenceTransformer model.
	"""

	return SentenceTransformer(
		settings.sentence_transformers_model,
		device=get_device()
	)


def calculate_similarity(
	expected_answer: str,
	generated_answer: str,
	similarity_model: SentenceTransformer
) -> float:
	"""
	Calculate semantic similarity between two answers.

	Args:
		expected_answer:
			Ground truth answer.

		generated_answer:
			Answer produced by the RAG system.

		similarity_model:
			SentenceTransformer model.

	Returns:
		Cosine similarity score.
	"""

	expected_embedding = similarity_model.encode(
		expected_answer,
		convert_to_tensor=True,
	)

	generated_embedding = similarity_model.encode(
		generated_answer,
		convert_to_tensor=True,
	)

	score = cos_sim(
		expected_embedding,
		generated_embedding
	)

	return float(score.item())


def evaluate_rag(
	question: str,
	expected_answer: str,
	generated_answer: str,
	similarity_model: SentenceTransformer
) -> dict:
	"""
	Evaluate a single RAG response.

	Args:
		question:
			User question.

		expected_answer:
			Ground truth answer.

		generated_answer:
			Answer generated by the RAG system.

		similarity_model:
			SentenceTransformer model.

		Returns:
			Dictionary containing evaluation metrics.
	"""

	similarity = calculate_similarity(
		expected_answer=expected_answer,
		generated_answer=generated_answer,
		similarity_model=similarity_model
	)

	if similarity >= 0.90:
		status = "Excellent"

	elif similarity >= 0.75:
		status = "Good"

	elif similarity >= 0.50:
		status = "Fair"

	else:
		status = "Poor"

	return {
		"question": question,
		"expected_answer": expected_answer,
		"generated_answer": generated_answer,
		"similarity": round(similarity, 4),
		"status": status
	}